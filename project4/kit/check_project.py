def static():
    for f in ["template.yaml", "access-events/app.py", "access-events/chalicelib/validate.py",
              "access-events/chalicelib/model.py", "access-events/tests/test_app.py",
              "access-events/.chalice/config.json", "access-events/.chalice/policy-dev.json"]:
        if not os.path.exists(f):
            problems.append(f"{f} missing")
    template = read("template.yaml") or ""
    if "event_key" in template:
        warnings.append("template.yaml still uses the starting key (event_key). Is that your design?")
    app = (read("access-events/app.py") or "") + (read("access-events/chalicelib/validate.py") or "") \
        + (read("access-events/chalicelib/model.py") or "")
    if "NotImplementedError" in app:
        problems.append("NotImplementedError left in app.py / validate.py / model.py")
    if "TODO" in (read("access-events/.chalice/policy-dev.json") or "TODO"):
        problems.append("access-events/.chalice/policy-dev.json still has TODO")

    try:
        env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}  # write nothing, so chalice local does not reload
        out = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd="access-events",
                             capture_output=True, text=True, timeout=180, env=env).stdout
        passed = int((re.search(r"(\d+) passed", out) or [0, 0])[1])
        failed = int((re.search(r"(\d+) (failed|error)", out) or [0, 0])[1])
        line = f"pytest: {passed} passed, {failed} failed (need at least {MIN_TESTS} passing, none failing)"
        (ok if passed >= MIN_TESTS and failed == 0 else problems).append(line)
    except (OSError, subprocess.SubprocessError) as e:
        problems.append(f"Could not run pytest: {e}")

    readme = read("README.md") or ""
    missing = [h for h in README_HEADINGS if not re.search(rf"^#+\s*{re.escape(h)}", readme, re.I | re.M)]
    (problems if missing else ok).append("README.md is missing headings: " + ", ".join(missing) if missing
                                         else "README.md has all required headings")
    left = len(re.findall(r"\bTODO\b|_\(replace", readme))
    if left:
        problems.append(f"README.md still has {left} TODO / '(replace' placeholders")
    images = re.findall(r"!\[[^\]]*\]\(([^)]+)\)", readme)
    broken = [i for i in images if not i.startswith("http") and not os.path.exists(i)]
    if broken:
        problems.append("README.md links images that do not exist: " + ", ".join(broken))
    docs = [f for f in glob.glob("docs/*") if f.lower().endswith((".png", ".jpg", ".jpeg", ".gif"))]
    (ok if len(docs) >= 2 else problems).append(
        f"{len(docs)} screenshot(s) in docs/ (need 2: Lambda terminal during chaos card C4, check_project.py output)")

    progress = read("PROGRESS.md") or ""
    empty = [s for s in SESSIONS if not (m := re.search(rf"##[^\n]*{s}[^\n]*\n(.*?)(?=\n## |\Z)", progress, re.S))
             or not re.search(r"Done:[ \t]*\S", m.group(1))]
    (warnings if empty else ok).append("PROGRESS.md has no 'Done:' entry for: " + ", ".join(empty) if empty
                                       else "PROGRESS.md has an entry for every session")

    tracked = git("ls-files", "--full-name", ".")
    if tracked is None:
        warnings.append("git is not available here, or this folder is not in a git repository.")
        return
    files = tracked.split()
    bad = [f for f in files if f.endswith((".env", ".duckdb", ".tmp")) or "/.venv/" in f or f.startswith(".venv/")
           or "/out/" in f or "/.chalice/deployed" in f or "/.chalice/deployments" in f or "__pycache__" in f]
    (problems if bad else ok).append(("git tracks files that must not be committed: " + ", ".join(bad[:8]))
                                     if bad else "git hygiene: no .env, .venv, out/, caches or deployments tracked")
    for must in ["README.md", "RUBRIC.md", "PROGRESS.md", "template.yaml", "access-events/app.py",
                 "access-events/chalicelib/validate.py", "access-events/chalicelib/model.py",
                 "access-events/tests/test_app.py", "access-events/.chalice/policy-dev.json"]:
        if not any(f.endswith("project4/" + must) or f == must for f in files):
            problems.append(f"{must} is not committed (git add it)")
    status = git("status", "--porcelain", ".")
    if status and status.strip():
        warnings.append("You have uncommitted changes: git add, commit and push before submitting.")
    remote = git("remote", "get-url", "origin") or ""
    if "ds3022-events" not in remote:
        warnings.append(f"origin points to '{remote.strip() or 'nothing'}', not your ds3022-events repo.")
    if not (git("tag", "--list", "dp4-submit") or "").strip():
        warnings.append("No tag dp4-submit yet. Create it LAST: git tag dp4-submit, then git push origin dp4-submit")
    else:
        ok.append("tag dp4-submit exists")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--static", action="store_true", help="skip the live end-to-end check")
    p.add_argument("--api", default="http://127.0.0.1:8000")
    a = p.parse_args()
    if not os.path.isdir("kit") or not os.path.isdir("access-events"):
        sys.exit("Run this from your project4 folder:  cd project4  then  python kit/check_project.py")
    if not a.static:
        live(a.api.rstrip("/"))
    static()
    print("\nData Project 4 pre-submission check\n" + "-" * 36)
    for line in ok:
        print("  OK    " + line)
    for line in warnings:
        print("  WARN  " + line)
    for line in problems:
        print("  FIX   " + line)
    print()
    if problems:
        print(f"NOT READY: {len(problems)} thing(s) to fix.")
        sys.exit(1)
    print("READY" + (" (read the warnings above)" if warnings else "") + ("" if not a.static else " (static checks only)"))


if __name__ == "__main__":
    main()
