"""Pre-submission check for Data Project 4. Run it from the project4 folder:

    python kit/check_project.py            # everything (needs the emulator, Lambda and API terminals running)
    python kit/check_project.py --static   # files, README, tests and git only (no emulator needed)

The live part uploads a fixed set of check files (date 2026-11-02, users chk1a to chk4d)
to your bucket, waits for your function to process them, then calls your API and
compares the answers with the API contract in BRIEF.md. Running it again is safe:
your pipeline is idempotent, so the answers must not change.

It prints READY or a list of what is still missing. It checks what the grader checks
first; it does not judge the quality of your code or your README. Do not edit this file.
"""
