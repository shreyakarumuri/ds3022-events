MIN_TESTS = 8
FIELDS = ["event_id", "building_code", "building_door_id", "user_identity", "access_time", "result"]

problems, warnings, ok = [], [], []


def read(path):
    try:
        with open(path, encoding="utf8") as f:
            return f.read()
    except OSError:
        return None


def git(*args):
    try:
        out = subprocess.run(["git", *args], capture_output=True, text=True, timeout=30)
        return out.stdout if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


# ---------------------------------------------------------------- the check set

D = _dp4.CHECK_DATE
D_BEFORE = (datetime.fromisoformat(D) - timedelta(days=1)).strftime("%Y-%m-%d")


def ce(reader, hhmmss, user, result="granted", tz="Z", n=0):
    b, door = reader.split("-")
    return {"event_id": f"{reader}-{D.replace('-', '')}{hhmmss.replace(':', '')}-c{n:03d}", "building_code": b,
            "building_door_id": door, "user_identity": user, "access_time": f"{D}T{hhmmss}{tz}", "result": result}


def check_set():
    f1 = [ce("J10-11", t, u, r, n=i) for i, (t, u, r) in enumerate([
        ("01:30:00", "chk1a", "granted"), ("05:59:00", "chk2b", "denied"), ("07:45:10", "chk3c", "granted"),
        ("08:02:00", "chk1a", "granted"), ("08:15:30", "chk4d", "granted"), ("09:00:00", "chk2b", "granted"),
        ("12:30:00", "chk1a", "denied"), ("13:05:00", "chk3c", "granted"), ("17:45:00", "chk4d", "granted"),
        ("23:10:00", "chk1a", "granted")])]
    f1_with_repeat = f1[:4] + [dict(f1[3])] + f1[4:]   # the reader sent one event twice in a row, in the same file
    f2 = [ce("A01-23", t, u, r, tz, n=20 + i) for i, (t, u, r, tz) in enumerate([
        ("00:30:00", "chk1a", "granted", "+01:00"), ("00:45:00", "chk2b", "granted", "+01:00"),
        ("08:10:00", "chk3c", "granted", "Z"), ("08:20:00", "chk1a", "granted", "Z"), ("10:00:00", "chk4d", "denied", "Z"),
        ("14:00:00", "chk2b", "granted", "Z"), ("16:30:00", "chk3c", "granted", "Z"), ("18:00:00", "chk1a", "granted", "Z")])]
    good3 = [ce("J10-12", t, u, n=40 + i) for i, (t, u) in enumerate([
        ("09:10:00", "chk2b"), ("09:20:00", "chk3c"), ("10:30:00", "chk4d"),
        ("11:00:00", "chk1a"), ("15:15:00", "chk2b"), ("16:40:00", "chk3c")])]
    bad3 = [ce("J10-12", "09:30:00", "chk4d", n=60 + i) for i in range(6)]
    bad3[0].pop("user_identity")                       # R1
    bad3[1]["building_code"] = "Z99"                   # R2
    bad3[2]["building_door_id"] = "7"                  # R3
    bad3[3]["user_identity"] = "Student 42"            # R4
    bad3[4]["access_time"] = "2099-01-01T00:00:00Z"    # R5
    bad3[5]["result"] = "maybe"                        # R6
    docs = {
        "check/J10-11/f1.json": _dp4.dumps({"reader": "J10-11", "uploaded_at": f"{D}T23:15:00Z", "events": f1_with_repeat}),
        "check/A01-23/f2.json": _dp4.dumps({"reader": "A01-23", "uploaded_at": f"{D}T18:05:00Z", "events": f2}),
        "check/J10-12/f3.json": _dp4.dumps({"reader": "J10-12", "uploaded_at": f"{D}T17:00:00Z", "events": good3 + bad3}),
        "check/J10-11/f6.json": _dp4.dumps({"reader": "J10-11", "uploaded_at": f"{D}T23:20:00Z", "events": f1[:3]}),
        "check/A01-23/f7.txt": _dp4.dumps({"reader": "A01-23", "uploaded_at": f"{D}T18:10:00Z", "events": f2[:1]}),
    }
    docs["check/J10-11/f4.json"] = docs["check/J10-11/f1.json"][:200]   # not valid JSON
    return f1, f2, good3, docs


def utc(e):
    t = datetime.fromisoformat(e["access_time"].replace("Z", "+00:00")).astimezone(timezone.utc)
    return {**e, "access_time": t.strftime("%Y-%m-%dT%H:%M:%SZ")}


# ---------------------------------------------------------------- live checks

def api_get(base, path):
    try:
        with urllib.request.urlopen(base + path, timeout=10) as r:
            return r.status, json.loads(r.read() or b"null")
    except urllib.error.HTTPError as e:
        return e.code, None
    except (urllib.error.URLError, OSError, ValueError) as e:
        return None, str(e)


def same_events(got, expected, order_desc=False):
    """Compare an API events list with the expected events (fields, values, order)."""
    if not isinstance(got, list):
        return "events is not a list"
    exp = sorted(expected, key=lambda e: e["access_time"], reverse=order_desc)
    if [g.get("event_id") for g in got] != [e["event_id"] for e in exp]:
        return f"expected event_ids {[e['event_id'][-4:] for e in exp]}, got {[str(g.get('event_id'))[-4:] for g in got]}"
    for g, e in zip(got, exp):
        diff = [f for f in FIELDS if str(g.get(f)) != str(e[f])]
        if diff:
            return f"event {e['event_id']}: wrong {', '.join(diff)} (e.g. {diff[0]}={g.get(diff[0])!r}, expected {e[diff[0]]!r})"
    return None


def live(base):
    try:
        s3, sqs = _aws.client("s3"), _aws.client("sqs")
        s3.head_bucket(Bucket=_dp4.BUCKET)
    except Exception as e:  # noqa: BLE001
        problems.append(f"Bucket {_dp4.BUCKET} not reachable ({type(e).__name__}). Emulator terminal: moto_server -p 9324; then python kit/stack.py create.")
        return
    for _ in range(8):  # chalice local restarts by itself when your files change: give it a moment
        status, body = api_get(base, "/files")
        if status is not None:
            break
        time.sleep(2)
    if status is None:
        problems.append(f"API not reachable at {base} ({body}). API terminal: cd access-events, chalice local --stage local --port 8000")
        return
    notif = s3.get_bucket_notification_configuration(Bucket=_dp4.BUCKET)
    if not notif.get("QueueConfigurations"):
        problems.append("The bucket has no trigger. Lambda terminal: start (or restart) python kit/local_lambda.py")
        return

    f1, f2, good3, docs = check_set()
    t0 = datetime.now(timezone.utc) - timedelta(seconds=2)
    order = ["check/J10-11/f1.json", "check/A01-23/f2.json", "check/J10-12/f3.json", "check/J10-11/f4.json",
             "check/J10-11/f1.json", "check/J10-11/f6.json", "check/A01-23/f7.txt"]
    for key in order:                                    # f1 twice: the same file uploaded again
        s3.put_object(Bucket=_dp4.BUCKET, Key=key, Body=docs[key].encode("utf-8"))
    print(f"Uploaded {len(order)} check files to s3://{_dp4.BUCKET}/check/ ... waiting for your function", flush=True)

    expect_keys = {"check/J10-11/f1.json", "check/A01-23/f2.json", "check/J10-12/f3.json",
                   "check/J10-11/f4.json", "check/J10-11/f6.json"}
    rows, deadline = {}, time.time() + 60
    while time.time() < deadline:
        status, files = api_get(base, "/files")
        if status == 200 and isinstance(files, list):
            rows = {}
            for r in files:
                try:
                    when = datetime.fromisoformat(str(r.get("processed_at")).replace("Z", "+00:00"))
                    when = when if when.tzinfo else when.replace(tzinfo=timezone.utc)
                except ValueError:
                    continue
                if str(r.get("file_key", "")).startswith("check/") and when >= t0:
                    rows[r["file_key"]] = r
            if expect_keys <= set(rows):
                break
        time.sleep(2)
    missing = sorted(expect_keys - set(rows))
    if missing:
        problems.append(f"Not processed within 60 s: {', '.join(missing)}. Is kit/local_lambda.py running in the Lambda terminal? "
                        "Any ERROR lines there? Does /files return file_key and processed_at (ISO 8601)?")
    else:
        ok.append("All 5 check files processed (the same file twice included)")
    time.sleep(3)  # let the re-upload of f1 finish

    def expect(name, cond, detail=""):
        (ok if cond else problems).append(f"{name}" + ("" if cond else f": {detail}"))

    r = rows.get("check/J10-12/f3.json", {})
    expect("files: f3 (6 good + 6 bad) logged as partial, valid 6, rejected 6",
           r.get("status") == "partial" and str(r.get("valid")) == "6" and str(r.get("rejected")) == "6",
           f"got status={r.get('status')} valid={r.get('valid')} rejected={r.get('rejected')}")
    r = rows.get("check/J10-11/f4.json", {})
    expect("files: f4 (not JSON) logged as rejected", r.get("status") == "rejected", f"got status={r.get('status')}")
    r = rows.get("check/J10-11/f6.json", {})
    expect("files: f6 (reader retry, 3 known events) logged as ok", r.get("status") == "ok", f"got status={r.get('status')}")
    _, files = api_get(base, "/files")
    if isinstance(files, list):
        keys = [f.get("file_key") for f in files]
        expect("files: one row per file (f1 uploaded twice)", keys.count("check/J10-11/f1.json") == 1,
               f"f1 appears {keys.count('check/J10-11/f1.json')} times")
        expect("files: the .txt file did not trigger the function", "check/A01-23/f7.txt" not in keys, "f7.txt was processed")

    j10 = [utc(e) for e in f1 + good3]
    a01 = [utc(e) for e in f2]
    s, b = api_get(base, f"/buildings/J10/access?date={D}")
    expect("GET /buildings/J10/access: 16 events, in time order, no duplicates", s == 200 and isinstance(b, dict)
           and b.get("count") == 16 and not same_events(b.get("events"), j10),
           f"HTTP {s}, " + (f"count={b.get('count')}, {same_events(b.get('events'), j10)}" if isinstance(b, dict) else str(b)))
    for day, exp in [(D, [e for e in a01 if e["access_time"].startswith(D)]),
                     (D_BEFORE, [e for e in a01 if e["access_time"].startswith(D_BEFORE)])]:
        s, b = api_get(base, f"/buildings/A01/access?date={day}")
        expect(f"GET /buildings/A01/access?date={day}: {len(exp)} events (times converted to UTC)",
               s == 200 and isinstance(b, dict) and b.get("count") == len(exp) and not same_events(b.get("events"), exp),
               f"HTTP {s}, " + (f"count={b.get('count')}, {same_events(b.get('events'), exp)}" if isinstance(b, dict) else str(b)))
    ah = [e for e in j10 if e["result"] == "granted" and _dp4.after_hours(e["access_time"]) and e["access_time"].startswith(D)]
    s, b = api_get(base, f"/buildings/J10/after-hours?date={D}")
    expect(f"GET /buildings/J10/after-hours: {len(ah)} granted entries between 22:00 and 06:00 UTC",
           s == 200 and isinstance(b, dict) and b.get("count") == len(ah) and not same_events(b.get("events"), ah),
           f"HTTP {s}, " + (f"count={b.get('count')}, {same_events(b.get('events'), ah)}" if isinstance(b, dict) else str(b)))
    s, _ = api_get(base, "/buildings/J10/access")
    expect("GET /buildings/J10/access without a date: HTTP 400", s == 400, f"HTTP {s}")
    mine = sorted([e for e in j10 + a01 if e["user_identity"] == "chk1a"], key=lambda e: e["access_time"], reverse=True)[:3]
    s, b = api_get(base, "/users/chk1a/access?limit=3")
    expect("GET /users/chk1a/access?limit=3: the 3 newest, newest first",
           s == 200 and isinstance(b, dict) and b.get("count") == 3 and not same_events(b.get("events"), mine, order_desc=True),
           f"HTTP {s}, " + (f"count={b.get('count')}, {same_events(b.get('events'), mine, True)}" if isinstance(b, dict) else str(b)))
    target = a01[0]
    s, b = api_get(base, f"/events/{target['event_id']}")
    expect("GET /events/{id}: the event, with access_time in UTC",
           s == 200 and isinstance(b, dict) and not [f for f in FIELDS if str(b.get(f)) != str(target[f])],
           f"HTTP {s}, got {b}")
    s, _ = api_get(base, "/events/check-no-such-event")
    expect("GET /events/{id} for an unknown id: HTTP 404", s == 404, f"HTTP {s}")

    try:
        url = sqs.get_queue_url(QueueName=_dp4.DLQ)["QueueUrl"]
        n = int(sqs.get_queue_attributes(QueueUrl=url, AttributeNames=["ApproximateNumberOfMessages"])
                ["Attributes"]["ApproximateNumberOfMessages"])
        (ok if n == 0 else warnings).append(f"{n} event(s) waiting in the dead-letter queue" +
                                            ("" if n == 0 else ": fix the cause, then python kit/redrive.py --go"))
    except Exception:  # noqa: BLE001
        pass


